"""
Generate every results table of the paper directly from the authority files,
so no number is typed by hand.

Usage (from the repository root):
    python <path>/make_tables.py --logs logs --out <paper>/tables
Reads:  logs/final_results_v2.json, logs/null_baseline.json, logs/losses_{tag}_seed{S}.json
Writes: tables/*.tex (one table body per file)
"""
import os, json, argparse
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("--logs", default="logs")
ap.add_argument("--out", default="tables")
a = ap.parse_args()
os.makedirs(a.out, exist_ok=True)
V2 = json.load(open(os.path.join(a.logs, "final_results_v2.json")))
NB = json.load(open(os.path.join(a.logs, "null_baseline.json")))
C, R = V2["configs"], V2["references"]
SEEDS = [42, 123, 2024]

def ms(x, d=2):
    if not x or not x.get("n"):
        return "--"
    return f"{x['mean']:.{d}f} $\\pm$ {x['std']:.{d}f}" if x.get("std") is not None else f"{x['mean']:.{d}f}"

def sgn(x, d=2):
    """Signed number with a proper LaTeX minus."""
    s = f"{x:+.{d}f}"
    return "$-$" + s[1:] if s.startswith("-") else s

def write(name, body):
    with open(os.path.join(a.out, name), "w", encoding="utf-8") as f:
        f.write("% AUTO-GENERATED by tools/make_tables.py from logs/ -- do not edit by hand\n" + body)
    print("wrote", name)

# ── Table 1: main results ──────────────────────────────────────────────────────
rows = [("Centralized, 15k steps", "central_gan", "central_cgan"),
        ("Centralized, 3k steps", "central_gan_3k", "central_cgan_3k"),
        ("Federated, IID", "iid", "cgan_iid"),
        ("Federated, non-IID (fixed)", "non_iid", "cgan_non_iid"),
        ("Federated, non-IID (per-seed)", "gan_non_iid_perseed_syncG", "cgan_non_iid_perseed_syncG"),
        ("Federated, noisy client", "noisy_client", "cgan_noisy_client"),
        ("Federated, IID, Sync D\\&G", None, "cgan_iid_syncDG"),
        ("Federated, non-IID (fixed), Sync D\\&G", None, "cgan_non_iid_syncDG")]
b = []
for name, g, c in rows:
    gs = C[g]["summary"] if g else {}
    cs = C[c]["summary"]
    mark = "$^\\dagger$" if g == "central_gan_3k" else ""
    b.append(f"{name} & {ms(gs.get('fid')) if g else '--'} & {ms(gs.get('pseudo_acc')) + mark if g else '--'} & "
             f"{ms(cs['fid'])} & {ms(cs['acc'])} \\\\")
b.append("\\midrule")
b.append(f"Real data, all 89{{,}}996 images & -- & -- & -- & {ms(R['real_full'])} \\\\")
b.append(f"Real data, 10{{,}}000-image subset & -- & -- & -- & {ms(R['real_matched_10k'])} \\\\")
write("tab_main.tex", "\n".join(b) + "\n")

# ── Table 2: generator-loss change, both anchors ───────────────────────────────
def deltas(tag):
    r5, r15 = [], []
    for s in SEEDS:
        g = np.array(json.load(open(os.path.join(a.logs, f"losses_{tag}_seed{s}.json")))["g_loss"], float)
        r5.append(g[-5:].mean() - g[4]); r15.append(g[-5:].mean() - g[:5].mean())
    return r5, r15
lrows = [("cGAN, Sync-G, non-IID (fixed)", "cgan_non_iid"),
         ("cGAN, Sync-G, non-IID (per-seed)", "cgan_non_iid_perseed_syncG"),
         ("cGAN, Sync D\\&G, non-IID (fixed)", "cgan_non_iid_syncDG"),
         ("cGAN, Sync-G, IID", "cgan_iid"),
         ("cGAN, Sync D\\&G, IID", "cgan_iid_syncDG"),
         ("cGAN, Sync-G, noisy client", "cgan_noisy_client"),
         ("GAN, Sync-G, IID", "iid"),
         ("GAN, Sync-G, non-IID (fixed)", "non_iid"),
         ("GAN, Sync-G, non-IID (per-seed)", "gan_non_iid_perseed_syncG"),
         ("GAN, Sync-G, noisy client", "noisy_client")]
b = []
for name, tag in lrows:
    r5, r15 = deltas(tag)
    up = sum(x > 0 for x in r5)
    b.append(f"{name} & {sgn(min(r5))} to {sgn(max(r5))} & {sgn(np.mean(r15), 3)} & {up}/3 \\\\")
write("tab_loss.tex", "\n".join(b) + "\n")

# ── Appendix: per-seed values ─────────────────────────────────────────────────
order = [("central_gan", "GAN, centralized 15k", "pseudo_acc"), ("central_gan_3k", "GAN, centralized 3k", "pseudo_acc"),
         ("iid", "GAN, IID", "pseudo_acc"), ("non_iid", "GAN, non-IID (fixed)", "pseudo_acc"),
         ("gan_non_iid_perseed_syncG", "GAN, non-IID (per-seed)", "pseudo_acc"), ("noisy_client", "GAN, noisy client", "pseudo_acc"),
         ("central_cgan", "cGAN, centralized 15k", "acc"), ("central_cgan_3k", "cGAN, centralized 3k", "acc"),
         ("cgan_iid", "cGAN, IID", "acc"), ("cgan_non_iid", "cGAN, non-IID (fixed)", "acc"),
         ("cgan_non_iid_perseed_syncG", "cGAN, non-IID (per-seed)", "acc"), ("cgan_noisy_client", "cGAN, noisy client", "acc"),
         ("cgan_iid_syncDG", "cGAN, IID, Sync D\\&G", "acc"), ("cgan_non_iid_syncDG", "cGAN, non-IID (fixed), Sync D\\&G", "acc")]
b = []
for tag, name, m in order:
    s = C[tag]["summary"]
    f = " / ".join(f"{v:.1f}" for v in s["fid"]["values"])
    acc = " / ".join(f"{v:.1f}" for v in s[m]["values"])
    inst = C[tag].get("instrument_sd")
    b.append(f"{name} & {f} & {acc} & {inst:.2f} \\\\" if inst is not None else f"{name} & {f} & {acc} & -- \\\\")
write("tab_perseed.tex", "\n".join(b) + "\n")

# ── Appendix: Welch table ─────────────────────────────────────────────────────
b = []
for w in NB["welch"]:
    lab = (w["label"].replace("&", "\\&").replace("  ", " ")
                     .replace(" - ", " $-$ ").replace("frozen", "fixed"))
    pv = "$<$0.001" if w["welch_p"] < 0.001 else f"{w['welch_p']:.3f}"
    b.append(f"{lab} & {sgn(w['difference'])} & {sgn(w['welch_t'])} & {w['welch_df']:.1f} & {pv} \\\\")
write("tab_welch.tex", "\n".join(b) + "\n")

# ── Appendix: null baseline per configuration ─────────────────────────────────
names = {t: n for t, n, _ in order}
b = []
for tag, c in NB["configs"].items():
    ns, nf = c["null_selected"], c["null_final_epoch"]
    obs = " / ".join(f"{v:.1f}" for v in c["observed_seed_values"])
    b.append(f"{names.get(tag, tag)} & {ns['mean']:.1f} $\\pm$ {ns['std']:.1f} & {ns['p95']:.1f} & {ns['max']:.1f} & "
             f"{nf['mean']:.1f} & {obs} \\\\")
rn = NB["real_null"]
b.append("\\midrule")
b.append(f"Real images, permuted labels & {rn['selected']['mean']:.1f} $\\pm$ {rn['selected']['std']:.1f} & "
         f"{rn['selected']['p95']:.1f} & {rn['selected']['max']:.1f} & {rn['final_epoch']['mean']:.1f} & -- \\\\")
p = NB["pooled_synthetic_null"]
b.append(f"Pooled synthetic (n = {p['selected']['n']}) & {p['selected']['mean']:.1f} $\\pm$ {p['selected']['std']:.1f} & "
         f"{p['selected']['p95']:.1f} & {p['selected']['max']:.1f} & {p['final_epoch']['mean']:.1f} & -- \\\\")
write("tab_null.tex", "\n".join(b) + "\n")

# ── Numbers used in the text, for reference ────────────────────────────────────
pool = np.array([r["selected_acc"] for c in NB["configs"].values() for r in c["runs"]])
k3 = np.random.default_rng(0).choice(pool, (200000, 3)).mean(1)
with open(os.path.join(a.out, "numbers.txt"), "w") as f:
    f.write(f"null pooled selected mean {pool.mean():.1f} sd {pool.std(ddof=1):.1f} max {pool.max():.1f}\n")
    f.write(f"null mean-of-3 p95 {np.percentile(k3,95):.1f}\n")
    f.write(f"majority share {NB['baselines']['test_majority_share']:.1f}\n")
    for k, v in NB["spearman"].items():
        f.write(f"spearman {k}: rho {v['rho']:+.3f} n {v['n']} p {v['exact_null_p']:.3f}\n")
print("wrote numbers.txt")
